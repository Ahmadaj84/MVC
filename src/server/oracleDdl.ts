export const ORACLE_19C_NODE_CONNECTOR = `// Oracle 19c Node.js Connection Pool Setup (using oracledb)
// npm install oracledb
import oracledb from 'oracledb';

// Configure Oracle 19c Client mode (Thin or Thick driver)
// In Oracle 19c, the Thin driver works out of the box without Instant Client!
oracledb.outFormat = oracledb.OUT_FORMAT_OBJECT;
oracledb.autoCommit = true;

// Credentials MUST come from the environment / a secrets manager - never hardcode defaults.
for (const key of ['ORACLE_USER', 'ORACLE_PASSWORD', 'ORACLE_CONNECT_STRING']) {
  if (!process.env[key]) throw new Error(\`Missing required environment variable \${key}\`);
}

const oracleConfig = {
  user: process.env.ORACLE_USER,
  password: process.env.ORACLE_PASSWORD,
  connectString: process.env.ORACLE_CONNECT_STRING, // e.g. host:1521/SERVICE_NAME
  poolMin: 2,
  poolMax: 10,
  poolIncrement: 2
};

let pool;

export async function initOraclePool() {
  try {
    pool = await oracledb.createPool(oracleConfig);
    console.log('Connected successfully to Oracle Database 19c');
  } catch (err) {
    console.error('Oracle 19c connection pool error:', err);
    throw err;
  }
}

// Generic query executor for Oracle 19c
export async function executeQuery(sql, binds = [], opts = {}) {
  let conn;
  try {
    conn = await pool.getConnection();
    const result = await conn.execute(sql, binds, opts);
    return result.rows;
  } finally {
    if (conn) {
      await conn.close();
    }
  }
}
`;
